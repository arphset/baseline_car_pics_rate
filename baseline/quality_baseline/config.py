# Решение: фото приводится к стандартному размеру показа (длинная сторона 1024 px, как карточка
# объявления на экране), и резкость меряется уже на нём. Маленькое фото при увеличении
# становится мягким — и индекс это видит. Значения переводятся в [0, 1] по логарифмической шкале.
